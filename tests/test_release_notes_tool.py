"""tools/changelog_section.py: the body of a release is the section of the CHANGELOG, followed by the compatibility table when asked."""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import changelog_section as cs
import vendor_copy

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = "# Changelog\n\n## [Unreleased]\n\n- not yet\n\n## [0.3.9] - New\n\n- first\n- second\n\n## [0.3.8] - Before\n\n- older\n\n## [0.3.7]\n"


def test_the_body_of_a_version_is_its_section_alone():
    assert cs.section(SAMPLE, "0.3.9") == "- first\n- second\n"
    assert cs.section(SAMPLE, "0.3.8", with_heading=True).startswith("## [0.3.8] - Before\n\n- older")
    assert cs.section(SAMPLE, "0.3.7") is None and cs.section(SAMPLE, "9.9.9") is None and cs.section(SAMPLE, "0.3") is None
    assert cs.section(SAMPLE.replace("\n", "\r\n"), "0.3.8") == "- older\n"
    assert cs.section("## [0.8.0.1] - x\n\n- y\n", "0.8.0.1") == "- y\n"


def test_the_table_loses_its_generator_comment(tmp_path):
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "COMPATIBILITY.md").write_text("<!-- GENERATED by x -->\n\n## Compatibility\n\n| a | b |\n", encoding="utf-8")
    assert cs.compatibility_table(tmp_path).startswith("## Compatibility") and "GENERATED" not in cs.compatibility_table(tmp_path)
    assert cs.compatibility_table(tmp_path / "nowhere") is None


def test_a_program_that_carries_the_copies_gets_the_notes_with_the_table(tmp_path):
    program = tmp_path / "program"
    (program / "tools").mkdir(parents=True)
    (program / "docs").mkdir()
    (program / "CHANGELOG.md").write_text(SAMPLE, encoding="utf-8")
    shutil.copy(ROOT / "tools" / "changelog_section.py", program / "tools" / "changelog_section.py")
    run = lambda *args: subprocess.run([sys.executable, str(program / "tools" / "changelog_section.py"), *args], capture_output=True, text=True, check=False)  # noqa: E731
    assert run("0.3.9").stdout == "- first\n- second\n"
    missing = run("0.3.9", "--compat")
    assert missing.returncode == 1 and "docs/COMPATIBILITY.md is missing" in missing.stderr and "--set compat" in missing.stderr
    shutil.copy(ROOT / "docs" / "COMPATIBILITY.md", program / "docs" / "COMPATIBILITY.md")
    both = run("0.3.9", "--compat")
    assert both.returncode == 0 and both.stdout.startswith("- first\n- second\n\n") and "Protocol version" in both.stdout and "GENERATED" not in both.stdout
    assert run("99.9.9").returncode == 1 and run().returncode == 2 and run("latest").returncode == 2


def test_the_vendor_set_carries_the_tool():
    assert vendor_copy.SETS["release_notes"] == ["tools/changelog_section.py"]
